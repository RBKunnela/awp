/**
 * Generate full offline-verifiable AWP receipt bundles for all four profiles.
 *
 *   npm run build && node tools/generate-multi-profile-receipts.mjs
 *
 * Output:
 *   samples/receipts/{pay,doc,principal,composite}.json
 *   samples/receipt.json  (alias of pay — keeps existing walkthrough)
 *
 * Each file is self-contained: public key + envelope + inclusion + checkpoint + OTS.
 * `npx awp verify samples/receipts/<profile>.json` → PASS.
 *
 * Deterministic keys (fixed seeds) — reproducible. Chefe 1072 / TICKET-AWP-MULTI-PROFILE-EMIT-001.
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { createPrivateKey, createPublicKey, sign as edSign } from 'node:crypto';
import {
  signEnvelope,
  signerFromPrivateKey,
  ReferenceLog,
  checkpoint,
  proof,
  buildTestOtsProof,
} from '../dist/index.js';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');
const vectorsDir = join(root, 'test', 'schema', 'vectors');
const outDir = join(root, 'samples', 'receipts');
const samplesDir = join(root, 'samples');

const PROFILES = ['pay', 'doc', 'principal', 'composite'];

function ed25519FromSeed(seedText) {
  const seed = Buffer.from(seedText, 'utf8').subarray(0, 32);
  if (seed.length !== 32) throw new Error('seed must be >=32 bytes');
  const privDer = Buffer.concat([
    Buffer.from([
      0x30, 0x2e, 0x02, 0x01, 0x00, 0x30, 0x05, 0x06, 0x03, 0x2b, 0x65, 0x70, 0x04, 0x22, 0x04,
      0x20,
    ]),
    seed,
  ]);
  const privateKey = createPrivateKey({ key: privDer, format: 'der', type: 'pkcs8' });
  const publicKey = createPublicKey(privateKey);
  const rawPub = new Uint8Array(publicKey.export({ format: 'der', type: 'spki' }).subarray(-32));
  return { privateKey, publicKey, rawPub };
}

function buildReceiptForProfile(profile) {
  const record = JSON.parse(readFileSync(join(vectorsDir, `valid-${profile}.json`), 'utf8'));
  // Distinct seeds per profile so keys differ but stay deterministic
  const env = ed25519FromSeed(`awp-mp-${profile}-envelope-key-seed-32b!!`.padEnd(40, '!').slice(0, 40));
  const envelopeSigner = signerFromPrivateKey(env.privateKey, `awp-mp-${profile}-envelope`);
  const envelope = signEnvelope(record, envelopeSigner);
  const publicKeyPem = env.publicKey.export({ type: 'spki', format: 'pem' });
  const publicKeyRawB64 = Buffer.from(env.rawPub).toString('base64');

  const ORIGIN = `awp.example/witness-log-${profile}`;
  const log = new ReferenceLog(ORIGIN, { checkpointEvery: 4 });
  const ourLeaf = Buffer.from(envelope.payload, 'base64');
  const otherLeaves = [
    Buffer.from(`awp-mp-${profile}-sib-0`, 'utf8'),
    Buffer.from(`awp-mp-${profile}-sib-2`, 'utf8'),
    Buffer.from(`awp-mp-${profile}-sib-3`, 'utf8'),
  ];
  log.append(otherLeaves[0]);
  const ourIndex = log.append(ourLeaf);
  log.append(otherLeaves[1]);
  log.append(otherLeaves[2]);

  const logKey = ed25519FromSeed(`awp-mp-${profile}-logsign-key-seed-32b!!!!`.padEnd(40, '!').slice(0, 40));
  const noteSigner = {
    name: ORIGIN,
    publicKey: logKey.rawPub,
    sign: (bytes) => new Uint8Array(edSign(null, bytes, logKey.privateKey)),
  };
  const cp = checkpoint(log, noteSigner);
  const otsProof = buildTestOtsProof(Buffer.from(cp.rootHex, 'hex'), {
    confirmed: true,
    height: 842000,
  });
  const anchors = [
    {
      type: 'ots',
      checkpoint_root: cp.rootHex,
      ots_proof_b64: otsProof.toString('base64'),
      pending: false,
    },
  ];

  const bundle = proof(ourIndex, {
    store: log,
    record,
    envelope,
    signerPublicKey: logKey.rawPub,
    checkpoint: cp,
    anchors,
  });

  return {
    _comment: `Full AWP receipt profile=${profile}. Offline: npx awp verify samples/receipts/${profile}.json → PASS. Generated by tools/generate-multi-profile-receipts.mjs (Chefe 1072).`,
    profile,
    public_key_pem: publicKeyPem,
    public_key_raw_base64: publicKeyRawB64,
    ...bundle,
  };
}

mkdirSync(outDir, { recursive: true });
const results = {};
for (const profile of PROFILES) {
  const receipt = buildReceiptForProfile(profile);
  const path = join(outDir, `${profile}.json`);
  writeFileSync(path, JSON.stringify(receipt, null, 2) + '\n');
  results[profile] = path;
  console.log('wrote', path);
}

// Keep classic walkthrough sample as pay alias
const payReceipt = readFileSync(results.pay, 'utf8');
const payObj = JSON.parse(payReceipt);
payObj._comment =
  'AW-6 full receipt (pay). Alias of samples/receipts/pay.json. `awp verify samples/receipt.json` → PASS. Multi-profile siblings under samples/receipts/.';
writeFileSync(join(samplesDir, 'receipt.json'), JSON.stringify(payObj, null, 2) + '\n');
console.log('wrote samples/receipt.json (pay alias)');
console.log('done', Object.keys(results).join(', '));
